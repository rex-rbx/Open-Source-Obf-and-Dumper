local Ast = require("../ast");
local AstKind = Ast.AstKind;
local handlers = {};
handlers[AstKind.StringExpression] = require("./expressions/string");
handlers[AstKind.NumberExpression] = require("./expressions/number");
handlers[AstKind.BooleanExpression] = require("./expressions/boolean");
handlers[AstKind.NilExpression] = require("./expressions/nil");
handlers[AstKind.VariableExpression] = require("./expressions/variable");
handlers[AstKind.FunctionCallExpression] = require("./expressions/function_call");
handlers[AstKind.PassSelfFunctionCallExpression] = require("./expressions/pass_self_function_call");
handlers[AstKind.IndexExpression] = require("./expressions/index");
handlers[AstKind.NotExpression] = require("./expressions/not");
handlers[AstKind.NegateExpression] = require("./expressions/negate");
handlers[AstKind.LenExpression] = require("./expressions/len");
handlers[AstKind.OrExpression] = require("./expressions/or");
handlers[AstKind.AndExpression] = require("./expressions/and");
handlers[AstKind.TableConstructorExpression] = require("./expressions/table_constructor");
handlers[AstKind.FunctionLiteralExpression] = require("./expressions/function_literal");
handlers[AstKind.VarargExpression] = require("./expressions/vararg");
handlers[AstKind.IfElseExpression] = require("./expressions/if_else");
-- Binary ops share one handler
local binaryHandler = require("./expressions/binary");
handlers[AstKind.LessThanExpression] = binaryHandler;
handlers[AstKind.GreaterThanExpression] = binaryHandler;
handlers[AstKind.LessThanOrEqualsExpression] = binaryHandler;
handlers[AstKind.GreaterThanOrEqualsExpression] = binaryHandler;
handlers[AstKind.NotEqualsExpression] = binaryHandler;
handlers[AstKind.EqualsExpression] = binaryHandler;
handlers[AstKind.StrCatExpression] = binaryHandler;
handlers[AstKind.AddExpression] = binaryHandler;
handlers[AstKind.SubExpression] = binaryHandler;
handlers[AstKind.MulExpression] = binaryHandler;
handlers[AstKind.DivExpression] = binaryHandler;
handlers[AstKind.ModExpression] = binaryHandler;
handlers[AstKind.PowExpression] = binaryHandler;
return handlers;
